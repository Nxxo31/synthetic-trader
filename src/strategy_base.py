"""Strategy base class with plug-in interface for the paper trading engine.

This module defines the abstract base class and plug-in interface that all
trading strategies must implement. Strategies are registered in the
STRATEGY_REGISTRY and discovered via the strategy_factory.
"""

from __future__ import annotations

import logging
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from enum import Enum
from typing import Any

logger = logging.getLogger(__name__)


class SignalType(Enum):
    """Types of trading signals."""
    LONG = "LONG"
    SHORT = "SHORT"
    NO_SIGNAL = "NO_SIGNAL"


@dataclass
class Signal:
    """Trading signal generated by a strategy.

    Attributes:
        type: SignalType (LONG, SHORT, NO_SIGNAL)
        symbol: Trading symbol
        entry_price: Entry price for the trade
        stop_loss: Stop loss price
        take_profit: Take profit price
        duration_seconds: Duration of the contract in seconds
        confidence: Confidence score 0.0 to 1.0
        metadata: Additional metadata dictionary
    """

    type: SignalType
    symbol: str
    entry_price: float
    stop_loss: float
    take_profit: float
    duration_seconds: int
    confidence: float
    metadata: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self):
        if self.metadata is None:
            self.metadata = {}


class Strategy(ABC):
    """Abstract base class for all trading strategies.

    Subclasses must implement generate_signal() and get_win_probability().
    Strategies are registered in the STRATEGY_REGISTRY for discovery via
    the strategy factory.

    The plug-in interface allows new strategies to be added without
    modifying core engine code — just register them in the registry.
    """

    def __init__(self, name: str, symbol: str):
        self.name = name
        self.symbol = symbol

    @abstractmethod
    def generate_signal(self, data: Any) -> Signal:
        """Analyze market data and generate a trading signal.

        Args:
            data: Market data (DataFrame, candles, ticks, etc.)

        Returns:
            Signal with entry/exit/stop or NO_SIGNAL
        """
        ...  # pragma: no cover

    @abstractmethod
    def get_win_probability(self, signal: Signal) -> float:
        """Estimate win probability for Kelly sizing.

        Args:
            signal: The signal to estimate win probability for

        Returns:
            Win probability as a float between 0.0 and 1.0
        """
        ...  # pragma: no cover


class StrategyRegistry:
    """Plug-in registry for strategy discovery.

    Maps strategy names to their concrete classes. External code can
    register new strategies without modifying the core module.
    """

    def __init__(self) -> None:
        self._registry: dict[str, type] = {}
        self._config_registry: dict[str, type] = {}

    def register(
        self,
        name: str,
        cls: type,
        config_cls: type | None = None,
    ) -> None:
        """Register a strategy class under a canonical name.

        Args:
            name: Canonical name (lowercase, used for lookup)
            cls: Strategy subclass
            config_cls: Optional config class for this strategy
        """
        key = name.lower().strip()
        self._registry[key] = cls
        if config_cls is not None:
            self._config_registry[key] = config_cls
        logger.info("Registered strategy '%s' -> %s", name, cls.__name__)

    def create(
        self,
        name: str,
        symbol: str = "R_100",
        **kwargs: Any,
    ) -> Any:
        """Create a strategy instance by name.

        Args:
            name: Strategy name (case-insensitive on lookup)
            symbol: Trading symbol
            **kwargs: Extra arguments forwarded to strategy constructor

        Returns:
            Instantiated Strategy subclass

        Raises:
            ValueError: if the strategy name is not registered
        """
        key = name.lower().strip()
        if key not in self._registry:
            available = ", ".join(sorted(self._registry.keys()))
            msg = f"Unknown strategy '{name}'. Available: {available}"
            raise ValueError(msg)

        cls = self._registry[key]
        # ConfluenceStrategy needs sub-strategy instances, not raw config
        if key == "confluence":
            return cls(symbol=symbol, **kwargs)

        return cls(symbol=symbol, **kwargs)

    def list_strategies(self) -> list[str]:
        """Return canonical strategy names (one per distinct class)."""
        seen: set[int] = set()
        result: list[str] = []
        for name, cls in self._registry.items():
            if id(cls) not in seen:
                result.append(name)
                seen.add(id(cls))
        return result

    def available_strategies(self) -> dict[str, str]:
        """Return mapping of strategy names to their class names."""
        seen: set[str] = set()
        mapping: dict[str, str] = {}
        for name, cls in self._registry.items():
            cls_name = cls.__name__
            if cls_name not in seen:
                mapping[name] = cls_name
                seen.add(cls_name)
        return mapping


# Global registry instance - manually populate after imports
_default_registry = StrategyRegistry()

# Expose the default registry as 'default_registry'
default_registry = _default_registry

# Convenience aliases
__all__ = [
    "SignalType",
    "Signal",
    "Strategy",
    "StrategyRegistry",
    "default_registry",
    "register_strategy",
    "create_strategy",
    "list_strategies",
    "available_strategies",
]


def register_strategy(name: str, cls: type, config_cls: type | None = None) -> None:
    """Convenience function to register a strategy in the default registry."""
    _default_registry.register(name, cls, config_cls)


def create_strategy(name: str, symbol: str = "R_100", **kwargs: Any) -> Any:
    """Convenience function to create a strategy from the default registry."""
    return _default_registry.create(name, symbol, **kwargs)


def list_strategies() -> list[str]:
    """Convenience function to list registered strategies."""
    return _default_registry.list_strategies()


def available_strategies() -> dict[str, str]:
    """Convenience function to show available strategies."""
    return _default_registry.available_strategies()
